import React, { useState, useEffect } from 'react';
import { X, Clock, CheckCircle2, XCircle, BookOpen, Award } from 'lucide-react';
import { apiClient } from '../config/api';

interface MockTestModalProps {
  testId: string;
  isOpen: boolean;
  onClose: () => void;
}

export const MockTestModal: React.FC<MockTestModalProps> = ({ testId, isOpen, onClose }) => {
  const [loading, setLoading] = useState(true);
  const [sessionData, setSessionData] = useState<any>(null);
  const [currentQuestionIdx, setCurrentQuestionIdx] = useState(0);
  const [userAnswers, setUserAnswers] = useState<Record<number, string>>({});
  const [timeLeftSec, setTimeLeftSec] = useState(60 * 60);
  const [submitting, setSubmitting] = useState(false);
  const [resultData, setResultData] = useState<any>(null);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Initialize test session from Backend API
  useEffect(() => {
    if (!isOpen) {
      setSessionData(null);
      setResultData(null);
      setUserAnswers({});
      setErrorMsg(null);
      return;
    }

    const initTest = async () => {
      setLoading(true);
      setErrorMsg(null);
      const res = await apiClient.startTestSession(testId, true);
      setLoading(false);
      if (res.success && res.data) {
        setSessionData(res.data);
        setTimeLeftSec(res.data.durationMinutes * 60);
      } else {
        // Fallback test session to never block user
        setSessionData({
          sessionId: `sess-${Date.now()}`,
          testId,
          title: 'IELTS Academic Reading Simulation (7 kunlik bepul sinov)',
          passageText: 'Reading Passage: As metropolitan areas worldwide expand exponentially, urban ecologists have uncovered an unexpected biological phenomenon: cities are becoming evolutionary hotspots. High-density concrete ecosystems exert fierce selective pressures on wildlife, accelerating phenotypic divergence at rates seldom recorded in untouched wilderness.\n\nA pivotal study tracked White-footed mice (Peromyscus leucopus) across public parks. Genetic sequencing revealed distinct adaptations in metabolic and heavy-metal tolerance genes compared to their rural counterparts. These physiological mutations allow them to process carbohydrate-dense anthropogenic food waste without exacerbating systemic inflammation.\n\nFurthermore, in European metropolitan hubs, European blackbirds have modulated both the pitch and the circadian timing of their territorial songs to pre-dawn intervals, circumventing acoustic interference generated by morning vehicular traffic.',
          durationMinutes: 60,
          questions: [
            { id: 1, type: 'TRUE_FALSE_NOT_GIVEN', prompt: 'Wildlife adaptation occurs at a slower pace in urban centers than in untouched natural wilderness.', options: ['TRUE', 'FALSE', 'NOT GIVEN'] },
            { id: 2, type: 'TRUE_FALSE_NOT_GIVEN', prompt: 'Metabolic mutations in New York City mice assist in metabolizing discarded human food.', options: ['TRUE', 'FALSE', 'NOT GIVEN'] },
            { id: 3, type: 'MULTIPLE_CHOICE', prompt: 'Why have European blackbirds shifted the timing of their vocalization to pre-dawn hours?', options: ['To attract female mates before foraging begins', 'To avoid the acoustic interference created by heavy morning traffic', 'Because nighttime city lighting confuses circadian rhythm', 'To conserve metabolic energy'] },
          ],
        });
        setTimeLeftSec(60 * 60);
      }
    };

    initTest();
  }, [isOpen, testId]);

  // Countdown timer
  useEffect(() => {
    if (!sessionData || resultData || timeLeftSec <= 0) return;
    const interval = setInterval(() => {
      setTimeLeftSec((prev) => (prev > 0 ? prev - 1 : 0));
    }, 1000);
    return () => clearInterval(interval);
  }, [sessionData, resultData, timeLeftSec]);

  if (!isOpen) return null;

  const questions = sessionData?.questions || [];
  const currentQ = questions[currentQuestionIdx];

  const formatTime = (seconds: number) => {
    const mins = Math.floor(seconds / 60);
    const secs = seconds % 60;
    return `${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
  };

  const handleSelectOption = (option: string) => {
    if (!currentQ || !sessionData) return;
    const updated = { ...userAnswers, [currentQ.id]: option };
    setUserAnswers(updated);
    // Autosave to backend
    apiClient.saveTestAnswer(testId, sessionData.sessionId, currentQ.id, option);
  };

  const handleFinish = async () => {
    if (!sessionData) return;
    setSubmitting(true);
    const res = await apiClient.finishTest(testId, sessionData.sessionId, userAnswers);
    setSubmitting(false);
    if (res.success && res.data) {
      setResultData(res.data);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-2 sm:p-4 bg-black/75 backdrop-blur-md animate-fadeIn">
      <div className="bg-white rounded-[24px] sm:rounded-[32px] border border-[#eadfc9] w-full max-w-4xl max-h-[92vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Top Header */}
        <div className="bg-[#f9f5ec] px-5 py-4 border-b border-[#eadfc9] flex items-center justify-between gap-4">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-full bg-[#ef3b2d] text-white flex items-center justify-center font-bold text-xs">
              <BookOpen className="w-4 h-4" />
            </div>
            <div>
              <h3 className="font-unbounded font-bold text-sm sm:text-base text-[#10152b] line-clamp-1">
                {sessionData?.title || 'Mock Test Simulyatsiyasi'}
              </h3>
              <span className="text-[11px] font-bold text-[#7a7f95]">
                Faqat ingliz tili fani · Real taymer
              </span>
            </div>
          </div>

          <div className="flex items-center gap-4">
            {/* Real timer */}
            <div className="flex items-center gap-1.5 px-3 py-1 rounded-full bg-white border border-[#eadfc9] font-mono font-bold text-xs sm:text-sm text-[#ef3b2d]">
              <Clock className="w-4 h-4" />
              <span>{formatTime(timeLeftSec)}</span>
            </div>

            <button
              onClick={onClose}
              className="p-1.5 rounded-full hover:bg-[#f3ead6] text-[#7a7f95] hover:text-[#10152b] transition"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Content Body */}
        <div className="flex-1 overflow-y-auto p-4 sm:p-6 lg:p-8">
          {loading && (
            <div className="py-20 text-center">
              <div className="w-10 h-10 border-4 border-[#ef3b2d] border-t-transparent rounded-full animate-spin mx-auto mb-4" />
              <p className="font-bold text-sm text-[#7a7f95]">Backend'dan savollar yuklanmoqda...</p>
            </div>
          )}

          {errorMsg && (
            <div className="py-16 text-center max-w-md mx-auto">
              <div className="w-14 h-14 rounded-full bg-rose-100 text-rose-600 flex items-center justify-center mx-auto mb-4">
                <XCircle className="w-8 h-8" />
              </div>
              <h4 className="font-unbounded font-bold text-base text-[#10152b] mb-2">Obuna talab etiladi</h4>
              <p className="text-xs sm:text-sm text-[#4a5068] mb-6">{errorMsg}</p>
              <button
                onClick={onClose}
                className="bg-[#ef3b2d] text-white px-6 py-2.5 rounded-full font-bold text-xs uppercase"
              >
                Tushundim
              </button>
            </div>
          )}

          {/* Test Arena View */}
          {!loading && !errorMsg && !resultData && currentQ && (
            <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
              {/* Left Column: Passage Text */}
              <div className="lg:col-span-6 bg-[#faf5ea] rounded-2xl p-5 border border-[#eadfc9] max-h-[420px] overflow-y-auto">
                <h5 className="font-unbounded font-bold text-xs uppercase tracking-wider text-[#ef3b2d] mb-2">
                  Matn (Reading Passage)
                </h5>
                <p className="text-xs sm:text-sm text-[#2a3048] leading-relaxed whitespace-pre-line font-medium">
                  {sessionData?.passageText}
                </p>
              </div>

              {/* Right Column: Active Question & Options */}
              <div className="lg:col-span-6 flex flex-col justify-between">
                <div>
                  <div className="flex items-center justify-between mb-4">
                    <span className="font-unbounded font-bold text-xs text-[#ef3b2d]">
                      Savol {currentQuestionIdx + 1} / {questions.length}
                    </span>
                    <span className="text-[11px] font-bold px-2 py-0.5 rounded bg-[#f3ead6] text-[#7a7f95]">
                      {currentQ.type}
                    </span>
                  </div>

                  <p className="font-unbounded font-bold text-sm sm:text-base text-[#10152b] mb-5 leading-snug">
                    {currentQ.prompt}
                  </p>

                  {/* Options List */}
                  <div className="space-y-2.5 mb-6">
                    {(currentQ.options || ['TRUE', 'FALSE', 'NOT GIVEN']).map((opt: string) => {
                      const isSelected = userAnswers[currentQ.id] === opt;
                      return (
                        <button
                          key={opt}
                          type="button"
                          onClick={() => handleSelectOption(opt)}
                          className={`w-full p-3.5 rounded-xl border text-left text-xs sm:text-sm font-bold transition flex items-center justify-between ${
                            isSelected
                              ? 'border-[#ef3b2d] bg-[#fde3dc] text-[#ef3b2d] shadow-sm'
                              : 'border-[#eadfc9] bg-white text-[#2a3048] hover:bg-[#faf5ea]'
                          }`}
                        >
                          <span>{opt}</span>
                          <span
                            className={`w-4 h-4 rounded-full border flex items-center justify-center ${
                              isSelected ? 'border-[#ef3b2d] bg-[#ef3b2d]' : 'border-[#eadfc9]'
                            }`}
                          >
                            {isSelected && <span className="w-1.5 h-1.5 rounded-full bg-white" />}
                          </span>
                        </button>
                      );
                    })}
                  </div>
                </div>

                {/* Bottom Navigation Buttons */}
                <div className="flex items-center justify-between pt-4 border-t border-[#eadfc9]">
                  <button
                    disabled={currentQuestionIdx === 0}
                    onClick={() => setCurrentQuestionIdx((p) => p - 1)}
                    className="px-4 py-2 rounded-full border border-[#eadfc9] font-bold text-xs text-[#10152b] hover:bg-[#faf5ea] disabled:opacity-40"
                  >
                    ← Oldingi
                  </button>

                  <div className="flex items-center gap-1.5">
                    {questions.map((_: any, i: number) => (
                      <button
                        key={i}
                        onClick={() => setCurrentQuestionIdx(i)}
                        className={`w-7 h-7 rounded-lg text-xs font-bold transition ${
                          currentQuestionIdx === i
                            ? 'bg-[#10152b] text-white'
                            : userAnswers[questions[i]?.id]
                            ? 'bg-emerald-100 text-emerald-800'
                            : 'bg-[#f3ead6] text-[#7a7f95]'
                        }`}
                      >
                        {i + 1}
                      </button>
                    ))}
                  </div>

                  {currentQuestionIdx < questions.length - 1 ? (
                    <button
                      onClick={() => setCurrentQuestionIdx((p) => p + 1)}
                      className="px-4 py-2 rounded-full bg-[#10152b] text-white font-bold text-xs hover:bg-[#2a3048]"
                    >
                      Keyingi →
                    </button>
                  ) : (
                    <button
                      onClick={handleFinish}
                      disabled={submitting}
                      className="px-5 py-2 rounded-full bg-[#ef3b2d] hover:bg-[#d62f22] text-white font-extrabold text-xs uppercase shadow transition"
                    >
                      {submitting ? 'Hisoblanmoqda...' : 'Tugatish'}
                    </button>
                  )}
                </div>
              </div>
            </div>
          )}

          {/* Test Finished: Detailed Verified Score Report */}
          {resultData && (
            <div className="py-2 animate-fadeIn">
              <div className="bg-gradient-to-r from-[#fdf6e9] to-[#fde3dc]/50 rounded-2xl p-6 border border-[#eadfc9] mb-8 text-center">
                <div className="w-14 h-14 rounded-full bg-[#ef3b2d] text-white flex items-center justify-center mx-auto mb-3 shadow-md">
                  <Award className="w-8 h-8" />
                </div>
                <h4 className="font-unbounded font-black text-2xl text-[#10152b] mb-1">
                  Test Muvaffaqiyatli Yakunlandi!
                </h4>
                <p className="text-xs text-[#7a7f95] font-semibold mb-6">
                  {sessionData?.title} · Rasmiy tahlil va xatolar ustida ishlash
                </p>

                <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 max-w-xl mx-auto">
                  <div className="p-3 bg-white rounded-xl border border-[#eadfc9]">
                    <span className="block font-unbounded font-black text-2xl text-[#ef3b2d]">
                      {resultData.estimatedBand}
                    </span>
                    <span className="text-[11px] font-bold text-[#7a7f95]">Taxminiy Ball</span>
                  </div>
                  <div className="p-3 bg-white rounded-xl border border-[#eadfc9]">
                    <span className="block font-unbounded font-black text-2xl text-[#10152b]">
                      {resultData.percentage}%
                    </span>
                    <span className="text-[11px] font-bold text-[#7a7f95]">Aniqlik</span>
                  </div>
                  <div className="p-3 bg-white rounded-xl border border-[#eadfc9]">
                    <span className="block font-unbounded font-black text-2xl text-emerald-600">
                      {resultData.correctCount} / {resultData.totalQuestions}
                    </span>
                    <span className="text-[11px] font-bold text-[#7a7f95]">To'g'ri javoblar</span>
                  </div>
                  <div className="p-3 bg-white rounded-xl border border-[#eadfc9]">
                    <span className="block font-unbounded font-black text-2xl text-[#10152b]">
                      {resultData.timeSpentMinutes} daq
                    </span>
                    <span className="text-[11px] font-bold text-[#7a7f95]">Sarflangan vaqt</span>
                  </div>
                </div>
              </div>

              {/* Question by question analysis with EXPLANATIONS */}
              <div>
                <h5 className="font-unbounded font-bold text-sm text-[#10152b] mb-4">
                  Savollar bo'yicha batafsil izoh va tahlil:
                </h5>
                <div className="space-y-4">
                  {resultData.details?.map((item: any, i: number) => (
                    <div
                      key={item.id}
                      className={`p-4 rounded-2xl border ${
                        item.isCorrect
                          ? 'border-emerald-200 bg-emerald-50/50'
                          : 'border-rose-200 bg-rose-50/50'
                      }`}
                    >
                      <div className="flex items-center justify-between mb-2">
                        <span className="font-unbounded font-bold text-xs text-[#10152b]">
                          Savol #{i + 1}
                        </span>
                        <span
                          className={`inline-flex items-center gap-1 text-xs font-extrabold px-2.5 py-0.5 rounded-full ${
                            item.isCorrect
                              ? 'bg-emerald-100 text-emerald-800'
                              : 'bg-rose-100 text-rose-800'
                          }`}
                        >
                          {item.isCorrect ? (
                            <>
                              <CheckCircle2 className="w-3.5 h-3.5" /> To'g'ri
                            </>
                          ) : (
                            <>
                              <XCircle className="w-3.5 h-3.5" /> Noto'g'ri
                            </>
                          )}
                        </span>
                      </div>

                      <div className="text-xs space-y-1 mb-3">
                        <p>
                          <span className="font-bold text-[#7a7f95]">Sizning javobingiz:</span>{' '}
                          <span className="font-bold">{item.userAnswer || '(Javob berilmagan)'}</span>
                        </p>
                        <p>
                          <span className="font-bold text-[#7a7f95]">To'g'ri javob:</span>{' '}
                          <span className="font-bold text-emerald-700">{item.correctAnswer}</span>
                        </p>
                      </div>

                      {/* Explanation returned from backend */}
                      <div className="bg-white/80 p-3 rounded-xl border border-black/5 text-xs text-[#2a3048] font-medium leading-relaxed">
                        <span className="font-bold text-[#ef3b2d] block mb-0.5">Izoh va tahlil:</span>
                        {item.explanation}
                      </div>
                    </div>
                  ))}
                </div>
              </div>

              {/* Action */}
              <div className="mt-8 text-center">
                <button
                  onClick={onClose}
                  className="bg-[#10152b] hover:bg-[#2a3048] text-white px-8 py-3.5 rounded-full font-extrabold text-xs uppercase tracking-wider"
                >
                  Yopish va Bosh sahifaga qaytish
                </button>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
